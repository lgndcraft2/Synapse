// ── Synapse PDF viewer ───────────────────────────────────────────
const viewerErrors = [];

function viewerUrl(fileUrl) {
  return `chrome-extension://${extensionId}/viewer/viewer.html?file=${encodeURIComponent(fileUrl)}`;
}

async function openViewer(fileUrl) {
  const v = await context.newPage();
  v.on('pageerror', (e) => viewerErrors.push(String(e)));
  v.on('console', (m) => { if (m.type() === 'error') viewerErrors.push(m.text()); });
  await v.goto(viewerUrl(fileUrl));
  return v;
}

/** The text-layer span whose text contains `needle`. */
function textSpan(v, needle) {
  return v.locator('#viewer .textLayer span', { hasText: needle }).first();
}

async function selectSpanText(v, needle) {
  await v.evaluate((n) => {
    const span = Array.from(document.querySelectorAll('#viewer .textLayer span')).find((s) => s.textContent.includes(n));
    const r = document.createRange();
    r.selectNodeContents(span);
    const sel = window.getSelection();
    sel.removeAllRanges();
    sel.addRange(r);
    document.dispatchEvent(new MouseEvent('mouseup', { bubbles: true }));
  }, needle);
}

