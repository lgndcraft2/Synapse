test.beforeAll(async () => {
  server = await startServer();
  port = server.address().port;
  base = `http://127.0.0.1:${port}`;
  const launched = await launchExtension({ args: ['--host-resolver-rules=MAP *.synapse.test 127.0.0.1'] });
  context = launched.context;
  extensionId = launched.extensionId;
  await writeStorage(launched.worker, {
    onboardingComplete: true,
    providerConfig: { backendBaseUrl: base, useBackendProxy: true, tier: 'free' },
  });
  for (const p of context.pages()) {
    if (p.url().includes('onboarding.html')) await p.close();
  }
  // The install-time onboarding tab can also open after this point and steal
  // focus (a blurred window cancels circle mode), so close it whenever it appears.
  context.on('page', async (p) => {
    try { await p.waitForLoadState('domcontentloaded'); } catch (_) { return; }
    if (p.url().includes('onboarding.html')) {
      await p.close().catch(() => {});
      await page?.bringToFront().catch(() => {});
    }
  });
  page = context.pages()[0] || (await context.newPage());
  page.on('console', (m) => { if (m.type() === 'error') consoleErrors.push(m.text()); });
  page.on('pageerror', (e) => consoleErrors.push(String(e)));
});

