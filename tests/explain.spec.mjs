test('discarded and expired captures are removed from storage.session; at most 4 are kept', async () => {
  await openArticle();
  await chordAround(page.locator('#p3'));
  await expect(page.locator('#synapse-confirm-bar')).toBeVisible();
  expect(await storedCaptureKeys()).toHaveLength(1);
  await page.keyboard.press('Escape');
  await expect.poll(storedCaptureKeys).toHaveLength(0);

  // Cap + expiry, exercised directly against the store.
  const result = await worker().evaluate(async () => {
    const fake = { base64: 'AAAA', mediaType: 'image/webp', thumbBase64: null, thumbDataUrl: null };
    const ids = [];
    for (let i = 0; i < 6; i++) ids.push(await storeCapture(fake, 999));
    const keysAfterCap = Object.keys(await chrome.storage.session.get(null)).filter((k) => k.startsWith('pendingCapture:'));
    const wrongTab = await takeCapture(ids[5], 1);           // another tab: refused (and dropped)
    const oldest = await takeCapture(ids[0], 999);           // evicted by the cap
    // Expire one: rewrite its record in storage and forget the memory copy.
    const key = 'pendingCapture:' + ids[4];
    const rec = (await chrome.storage.session.get(key))[key];
    await chrome.storage.session.set({ [key]: { ...rec, expiresAt: Date.now() - 1 } });
    pendingCaptures.delete(ids[4]);
    const expired = await takeCapture(ids[4], 999);
    const ok = await takeCapture(ids[3], 999);
    for (const id of ids) await dropCapture(id);
    const left = Object.keys(await chrome.storage.session.get(null)).filter((k) => k.startsWith('pendingCapture:'));
    return { capped: keysAfterCap.length, wrongTab, oldest, expired, ok: ok && ok.base64, left: left.length };
  });
  expect(result).toEqual({ capped: 4, wrongTab: null, oldest: null, expired: null, ok: 'AAAA', left: 0 });
});

