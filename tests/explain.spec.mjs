function json(res, status, body) {
  res.writeHead(status, { 'Content-Type': 'application/json' });
  res.end(JSON.stringify(body));
}

function readBody(req) {
  return new Promise((resolve) => {
    let raw = '';
    req.on('data', (c) => { raw += c; });
    req.on('end', () => resolve(JSON.parse(raw || '{}')));
  });
}

function startServer() {
  return new Promise((resolve) => {
    const srv = http.createServer(async (req, res) => {
      const url = new URL(req.url, 'http://x');
      if (req.method === 'GET' && url.pathname === '/article.html') {
        res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
        return res.end(ARTICLE);
      }
      if (req.method === 'GET' && url.pathname === '/settings.html') {
        res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
        return res.end(SETTINGS_PAGE);
      }
      if (req.method === 'GET' && url.pathname === '/notes.txt') {
        res.writeHead(200, { 'Content-Type': 'text/plain; charset=utf-8' });
        return res.end(NOTES);
      }
      if (req.method === 'GET' && url.pathname === '/paper.pdf') {
        res.writeHead(200, { 'Content-Type': 'application/pdf' });
        return res.end(SAMPLE_PDF);
      }
      if (req.method === 'GET' && url.pathname === '/locked.pdf') {
        res.writeHead(200, { 'Content-Type': 'application/pdf' });
        return res.end(PROTECTED_PDF);
      }
      if (req.method === 'GET' && url.pathname === '/broken.pdf') {
        res.writeHead(200, { 'Content-Type': 'application/pdf' });
        return res.end('this is not a pdf at all');
      }
      if (req.method === 'POST' && url.pathname === '/api/v1/explain') {
        const body = await readBody(req);
        requests.push(body);
        const re = body.reexplain;
        if (re) reexplainsServed += 1;
        const reply = explainQueue.shift() || {
          status: 200,
          body: {
            html: re
              ? `<p>Mock ${re.mode} version for ${body.kind}</p>`
              : `<p>Mock explanation for ${body.kind}</p>`,
            kind: body.kind,
            model_used: 'mock',
            history_entry: null,
            usage: null,
            reexplain: re ? { free: true, free_remaining: Math.max(0, 10 - reexplainsServed), free_limit: 10 } : null,
          },
        };
        setTimeout(() => json(res, reply.status, reply.body), 150);
        return;
      }
      if (req.method === 'POST' && url.pathname === '/api/v1/explain/context') {
        const body = await readBody(req);
        ctxUploads.push(body);
        ctxCounter += 1;
        // PDFs arrive as base64; the real backend extracts their text.
        const chars = (body.document_text || '').length || (body.document_base64 ? 4321 : 0);
        return json(res, 200, { context_id: `ctx-${ctxCounter}`, chars, truncated: false, expires_in: 3600 });
      }
      if (req.method === 'POST' && url.pathname === '/api/v1/reformat/reformat-document') {
        docReads.push(await readBody(req));
        return json(res, 200, { html: '<h2>Notes rebuilt</h2><p id="rebuilt">Rebuilt paragraph about plain notes and organelles.</p>' });
      }
      json(res, 404, { detail: 'not found' });
    });
    srv.listen(0, '127.0.0.1', () => resolve(srv));
  });
}

function worker() {
  const [sw] = context.serviceWorkers();
  if (!sw) throw new Error('service worker not running');
  return sw;
}

async function waitForRequests(n) {
  await expect.poll(() => requests.length, { timeout: 15_000 }).toBeGreaterThanOrEqual(n);
  return requests[n - 1];
}

