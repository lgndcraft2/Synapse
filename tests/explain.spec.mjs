/** Pending confirm-step captures in chrome.storage.session (the source of truth). */
async function storedCaptureKeys() {
  return worker().evaluate(async () => Object.keys(await chrome.storage.session.get(null)).filter((k) => k.startsWith('pendingCapture:')));
}

/** Stops the extension's MV3 service worker the way Chrome does when it is idle. */
async function stopServiceWorker() {
  const ext = await context.newPage();
  await ext.goto(`chrome-extension://${extensionId}/viewer/viewer.html`);
  const cdp = await context.newCDPSession(ext);
  const statuses = [];
  cdp.on('ServiceWorker.workerVersionUpdated', (e) => {
    for (const v of e.versions) if (v.scriptURL.endsWith('/background.js')) statuses.push(v.runningStatus);
  });
  await cdp.send('ServiceWorker.enable');
  await cdp.send('ServiceWorker.stopAllWorkers');
  await expect.poll(() => statuses[statuses.length - 1], { timeout: 10_000 }).toBe('stopped');
  await cdp.detach();
  await ext.close();
}

